if __name__ == "__main__":
    import numpy as np
    from PIL import Image
    for name, paths in PATHS.items():
        a = np.asarray(Image.open(f"public/images/{name}.png"))[..., 3]
        H, W = a.shape
        for pname, pts in paths.items():
            samples = []
            for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
                for t in np.linspace(0, 1, 30, endpoint=False):
                    samples.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t))
            on = np.mean([a[min(H - 1, int(y * H)), min(W - 1, int(x * W))] > 40 for x, y in samples]) * 100
            flag = "" if on >= 90 else "   <-- check"
            print(f"{name:18s} {pname:15s} {on:5.1f}% on drawing{flag}")
